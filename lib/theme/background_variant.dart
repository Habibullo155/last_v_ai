/// Варианты оформления фона — НЕ светлая/тёмная тема (это убрано осознанно:
/// у приложения глазморфизм-дизайн, весь текст белый по всему коду, и
/// честная светлая тема потребовала бы переписать цвет текста в каждом
/// месте, рискуя читаемостью без возможности визуально проверить результат.
/// Вместо этого — несколько вариантов ТЁМНОГО фона с разными акцентными
/// цветами: выглядит разнообразнее, но текст остаётся читаемым везде.
enum BackgroundVariant { violet, ocean, midnight }
